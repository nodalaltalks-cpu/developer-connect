/**
 * Founder-only team management. Every function calls requireFounderForAction FIRST (a Server Action is its own
 * network-callable endpoint); the staff service then refuses any non-FOUNDER actor a second time. People are invited by
 * the exact email they will sign in with; if an account with that email already exists its Clerk id is resolved here
 * on the server, and it is never typed or supplied by the browser. Nobody is ever deleted: they exit, and everything they
 * did stays. The employee ID is generated by the database and cannot be supplied or changed through any action here.
 */

export type StaffActionResult = { ok: true; message?: string } | { ok: false; error: string };

const GENERIC_ERROR = "Something went wrong. Please try again.";

function toResult(error: unknown): StaffActionResult {
  if (error instanceof StaffValidationError || error instanceof StaffStateError) return { ok: false, error: error.message };
  if (error instanceof StaffNotFoundError) return { ok: false, error: "That team member could not be found." };
  return { ok: false, error: GENERIC_ERROR };
}

/**
 * Invites a person (they have no access until you approve them and they sign in with that email). With a password, a new
 * email + password login is created for them in Clerk first; an email that already has a login is linked and its
 * password is never touched.
 */
export async function addStaffMemberAction(email: string, displayName: string, role: StaffRole = "EMPLOYEE", phone: string = "", password: string = ""): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  const actor: LeadActor = { actorType: "FOUNDER", actorId: founderId };
  try {
    const wantsPassword = typeof password === "string" && password.length > 0;
    if (wantsPassword) {
      const problem = passwordProblem(password);
      if (problem) return { ok: false, error: problem };
    }
    // An existing account with this email is linked now (still unapproved); otherwise the first sign-in links it. A lookup
    // failure is not an error: the invite works either way.
    const clerkUser = typeof email === "string" ? await findClerkUserByEmail(email).catch(() => null) : null;
    let userId = clerkUser?.id ?? null;
    let passwordSet = false;
    // Validate everything the invite needs BEFORE creating a login, so a typo never leaves an orphan login behind.
    const repo = createPostgresStaffRepository();
    if (wantsPassword && !userId) {
      validateInvite({ email, displayName, phone });
      const login = await createClerkLoginWithPassword({ email, password, displayName });
      if (!login.ok) return { ok: false, error: login.error };
      userId = login.userId;
      passwordSet = true;
    }
    const member = await inviteStaffMember(repo, { displayName, email, phone, role, userId }, actor);
    revalidatePath("/admin/staff");
    const base = `${member.employeeId} created. They cannot sign in to the team area until you approve them.`;
    if (passwordSet) return { ok: true, message: `${base} Login created: they sign in with ${member.email} and the password you set. Share it with them privately.` };
    if (wantsPassword && clerkUser) return { ok: true, message: `${base} That email already has a login, so its password was left unchanged; they sign in as they normally do.` };
    return { ok: true, message: base };
  } catch (error) {
    return toResult(error);
  }
}

export async function approveStaffMemberAction(staffId: string): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  try {
    const member = await approveStaffMember(createPostgresStaffRepository(), staffId, { actorType: "FOUNDER", actorId: founderId });
    revalidatePath("/admin/staff");
    revalidatePath(`/admin/staff/${member.employeeId}`);
    return { ok: true, message: member.status === "ACTIVE" ? `${member.employeeId} is approved and active.` : `${member.employeeId} is approved. They get access the first time they sign in with ${member.email}.` };
  } catch (error) {
    return toResult(error);
  }
}

/**
 * Blocks (active = false) or unblocks (active = true) a person. Blocking is one step: access stops at once (every access
 * check reads `active`), every open lead they own goes back to the Founder queue, and their login is banned so no
 * session survives. Unblocking lifts the ban and switches them back on; leads are not handed back automatically.
 */
export async function setStaffActiveAction(staffId: string, active: boolean): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  const actor: LeadActor = { actorType: "FOUNDER", actorId: founderId };
  const repo = createPostgresStaffRepository();
  let member;
  try {
    member = await setStaffActive(repo, staffId, active, actor);
  } catch (error) {
    return toResult(error);
  }
  let returned = 0;
  let remaining = 0;
  let loginNote = "";
  try {
    if (!active) {
      // Up to 500 leads per pass; a few passes cover any realistic book of leads.
      for (let pass = 0; pass < 6; pass++) {
        const r = await returnOpenLeadsToFounder(createPostgresLeadRepositories(), repo, actor, member.employeeId);
        returned += r.returned;
        remaining = r.remaining;
        if (r.returned === 0 || r.remaining === 0) break;
      }
    }
    // The Founder's own workspace record shares the Founder's login: never ban that.
    if (isLinked(member) && member.userId !== founderId) {
      const done = await setClerkBanned(member.userId, !active);
      if (!done) loginNote = active ? " Their login could not be unbanned automatically; check it in Clerk." : " Their team access is off, but their login could not be banned automatically; check it in Clerk.";
    }
  } catch {
    loginNote = " Access is off, but returning their leads or banning their login hit an error. Open their profile and run Return leads again.";
  }
  revalidatePath("/admin/staff");
  revalidatePath(`/admin/staff/${member.employeeId}`);
  revalidatePath("/admin/leads");
  const text = active
    ? `${member.employeeId} is unblocked and can sign in again.${loginNote}`
    : `${member.employeeId} is blocked. ${returned === 0 ? "They had no open leads." : `${returned} open lead${returned === 1 ? "" : "s"} returned to your queue${remaining > 0 ? `; ${remaining} remain, run Return leads again` : ""}.`}${loginNote}`;
  return { ok: true, message: text };
}

/** Sets a new password on an employee's login and signs them out everywhere else. The password is never stored. */
export async function resetStaffPasswordAction(staffId: string, password: string): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  try {
    const member = await createPostgresStaffRepository().getById(typeof staffId === "string" ? staffId : "");
    if (!member) return { ok: false, error: "That team member could not be found." };
    if (member.status === "EXITED") return { ok: false, error: `${member.employeeId} has exited.` };
    if (!isLinked(member)) return { ok: false, error: `${member.employeeId} has no login yet. Create it by adding them with a password, or wait for their first sign-in.` };
    if (member.userId === founderId) return { ok: false, error: "That is your own login. Change your own password in your account settings." };
    const result = await setClerkPassword(member.userId, password);
    if (!result.ok) return { ok: false, error: result.error };
    return { ok: true, message: `New password set for ${member.employeeId}. Any other device they were signed in on is signed out. Share it with them privately.` };
  } catch {
    return { ok: false, error: GENERIC_ERROR };
  }
}

/** Changes the approved login email. The employee ID, ownership and history never change; old and new address are logged. */
export async function changeStaffEmailAction(staffId: string, newEmail: string): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  try {
    const member = await changeStaffEmail(createPostgresStaffRepository(), staffId, newEmail, { actorType: "FOUNDER", actorId: founderId });
    revalidatePath("/admin/staff");
    revalidatePath(`/admin/staff/${member.employeeId}`);
    return { ok: true, message: `${member.employeeId}'s login email is now ${member.email}.` };
  } catch (error) {
    return toResult(error);
  }
}

/** Records that a person has left. Ends their access and keeps every record. */
export async function exitStaffMemberAction(staffId: string, reason: ExitReason): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  try {
    const member = await exitStaffMember(createPostgresStaffRepository(), staffId, reason, { actorType: "FOUNDER", actorId: founderId });
    revalidatePath("/admin/staff");
    revalidatePath(`/admin/staff/${member.employeeId}`);
    revalidatePath("/admin/leads");
    return { ok: true, message: `${member.employeeId} has exited. Their access is removed and their history is kept.` };
  } catch (error) {
    return toResult(error);
  }
}

/** Returns every open lead a person still owns to the Founder queue (history is kept; each return is an event). */
export async function returnOpenLeadsAction(employeeId: string): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  try {
    const { returned, remaining } = await returnOpenLeadsToFounder(createPostgresLeadRepositories(), createPostgresStaffRepository(), { actorType: "FOUNDER", actorId: founderId }, employeeId);
    revalidatePath("/admin/staff");
    revalidatePath("/admin/leads");
    return { ok: true, message: returned === 0 ? "They have no leads to return." : `${returned} lead${returned === 1 ? "" : "s"} returned to your queue${remaining > 0 ? `; ${remaining} remain (run it again)` : ""}.` };
  } catch (error) {
    return toResult(error);
  }
}

export interface HistoryRow {
  id: string;
  leadId: string;
  eventType: string;
  at: string;
}

/** The next page of what a person did (Founder only). */
export async function loadEmployeeHistoryAction(employeeId: string, beforeIso: string): Promise<{ ok: true; rows: HistoryRow[] } | { ok: false; error: string }> {
  const founderId = await requireFounderForAction();
  const before = new Date(beforeIso);
  if (Number.isNaN(before.getTime())) return { ok: false, error: "That page could not be loaded." };
  try {
    const events = await getEmployeeHistoryPage(createPostgresLeadRepositories(), createPostgresStaffRepository(), { actorType: "FOUNDER", actorId: founderId }, employeeId, before);
    return { ok: true, rows: events.map((e) => ({ id: e.id, leadId: e.leadId, eventType: e.eventType, at: e.createdAt.toISOString() })) };
  } catch {
    return { ok: false, error: GENERIC_ERROR };
  }
}

/** The Founder enrols themselves as the first team member, so their own calls and leads run through the team workspace and are tracked like anyone's. */
export async function enableMyWorkspaceAction(): Promise<StaffActionResult> {
  const founderId = await requireFounderForAction();
  try {
    const user = await currentUser();
    const verified = user?.emailAddresses.find((e) => e.verification?.status === "verified")?.emailAddress ?? null;
    // The team record carries the Founder's name as the public site states it, not whatever the sign-in account happens to be called.
    const name = FOUNDER.name;
    const { member, created } = await enrollFounderAsEmployee(createPostgresStaffRepository(), { userId: founderId, displayName: name, email: verified });
    revalidatePath("/admin/staff");
    return { ok: true, message: created ? `Your calling workspace is ready (${member.employeeId}).` : `Your calling workspace is already set up (${member.employeeId}).` };
  } catch (error) {
    return toResult(error);
  }
}
